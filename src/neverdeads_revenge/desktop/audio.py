"""Sound effects.

Two things had to be true for this to be worth having.

The first is that it is never *required*. A terminal game has no business
assuming it can make a noise, so this finds a device if there is one and does
nothing at all if there is not -- no error, no delay, no missing feature. The
sounds themselves are generated by ``tools/make_sounds.py`` and ship inside the
package.

The second is that it is never *late* -- and that is what the last two attempts
got wrong. Spawning a player per sound measured at 190ms and produced nothing at
all on the first blow of the first fight. One persistent ``aplay`` reading raw
samples from a pipe fixed the *spawn* cost and made it worse: the code scheduled
by its own clock and dropped by its own estimate of how far behind the device
was, and neither was measured. The device buffers hundreds of milliseconds and
the code never learns that, so half of a fight lands in the wrong order or does
not land at all -- thirteen sounds in a third of a second, and seven of them
dropped, which is exactly the erratic noise this used to be.

So the player is a library that owns its own audio thread and *asks* the code for
what to play: a callback stream, one ring buffer, and the one piece of state the
game was guessing at -- where the device is -- read straight off that buffer. A
sound is inserted behind whatever the device has not played yet, so the order is
the order they were queued in, and the drop decision is a comparison between two
measured numbers rather than a guess.

Turn it off with ``NEVERDEADS_REVENGE_MUTE=1``, with ``--no-sound``, or from the
pause menu, which remembers.

The library is ``miniaudio``. It is imported lazily, because a machine without it
-- or a build that shipped without -- is a game that is silent, not a game that
does not start.
"""

