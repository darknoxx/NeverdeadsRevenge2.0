#: Where the generated sounds live. Inside the package rather than in
#: ``assets/``: the icon is a desktop-file asset that only the installer reads,
#: and these are read at runtime, so they have to travel with the code.
SOUNDS_DIR = Path(__file__).resolve().parent.parent / "sounds"

#: The rate the sounds are generated at. ``tools/make_sounds.py`` writes it into
#: every file and the tests check they agree, and the device is opened at the
#: same rate, because a rate mismatch is a slow high-pitched version of the
#: whole soundtrack rather than an error anybody would find.
RATE = 11025

#: Set this to anything to start with the sound off. It can only ever mute --
#: a setting that says "on" cannot override it, because the one caller that
#: matters is the test suite.
MUTE_ENV = "NEVERDEADS_REVENGE_MUTE"

#: Set this to a path and every sound decision is appended to it.
#:
#: For the case where the sound is wrong and nobody can hear it from where the
#: code was written. The game cannot know whether a note came out of the
#: speaker, but it can say exactly what it asked for, when, and how far behind
#: the device already was -- and that is the difference between a bug and a
#: guess.
DEBUG_ENV = "NEVERDEADS_REVENGE_SOUND_LOG"

#: How far behind the device a sound may land before it is dropped rather than
#: queued.
#:
#: Measured, not guessed: it is the volume of the mixing buffer the device has
#: not played yet, in seconds. And with mixing it is a *net* rather than a
#: policy: two sounds in one turn play on top of each other, so the buffer's
#: length is **the longest clip still playing**, not the sum of everything
#: queued -- which is why this limit has to sit *above* the longest clip in the
#: pack (``dark_bell.wav``, 950ms) instead of below it. At 800ms every sound
#: queued while a bell or a level-up was ringing was dropped, and the one that
#: went missing most often was the fight's own sting: the letter came at the
#: camera in silence. A test holds this above the longest sound.
#:
#: What it is for: a device that stops draining must not turn a fight into a
#: queue three seconds behind itself.
MAX_BACKLOG = 1.20

#: How many failures in a row before the game gives up on sound.
#:
#: One was too few. A single hiccup -- a transient error from the audio server,
#: a device that cannot be opened -- used to silence the rest of the session, and
#: the player would hear nothing for the rest of the run without being told why.
#: A hiccup is not a broken machine; three in a row is.
GIVE_UP_AFTER = 3

#: Which sound a message gets, by the log's own classification.
#:
#: The log already sorts itself into combat, damage and the rest, so the sound
#: is a second reading of one classification rather than a second place for the
#: rules to be written down. The plainer kinds are silent on purpose: a sound
#: for every line is a sound for none of them.
